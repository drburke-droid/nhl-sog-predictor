"""Turn the saved experiment results into tables (results/summary.md + results/summary.json) and charts.

    python3 analyze.py
"""
import glob
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
GROUPS = ['brown', 'lightblue', 'pink', 'orange', 'red', 'yellow', 'green', 'darkblue']
NAMES = json.load(open(os.path.join(HERE, 'board.json')))['names']

LABEL = {
    'everything': 'Yes-Man (buy everything, hotels at once)',
    'nothing': 'Scrooge (buys nothing)',
    'railroads': 'Railroad Tycoon (railroads only)',
    'utilities': 'Utilities only',
    'infrastructure': 'Railroads + utilities only',
    'brown': 'Brown only', 'lightblue': 'Light blue only', 'pink': 'Pink only', 'orange': 'Orange only',
    'red': 'Red only', 'yellow': 'Yellow only', 'green': 'Green only',
    'darkblue': 'Boardwalk Dreamer (Park Place + Boardwalk only)',
    'prudent': 'Accountant (keeps $300 back)',
    'threehouses': 'Three-House Rule (stops at 3)',
    'houselock': 'House Hoarder (4 houses, never hotels)',
    'jailbird': 'Jailbird (always stays in jail)',
    'smartjail': 'Leaves jail early, stays late',
    'stubborn': 'Stubborn (never trades)',
    'shark': 'Shark (trades by set value)',
    'allin': 'All-In (mortgages to build, jail late)',
    'champion': 'Champion (combined playbook)',
}


def load(exp):
    out = {}
    for p in glob.glob(os.path.join(RES, exp, '*.json')):
        d = json.load(open(p))
        out[d['key']] = d
    return out


def pct(x):
    return 100.0 * x


def ci95(p, n):
    return 196.0 * math.sqrt(max(p * (1 - p), 1e-12) / n)


def table_rows(tables, world):
    rows = []
    for key, d in tables.items():
        w, t = key.split('__', 1)
        if w != world:
            continue
        p0 = d['players'][0]
        n = d['games']
        rows.append(dict(strategy=t, label=LABEL.get(t, t), win=pct(p0['wins'] / n), ci=ci95(p0['wins'] / n, n),
                         draws=pct(d['timeouts'] / n), games=n, got_set=pct(p0['got_set'] / n),
                         rounds=d['avg_rounds_finished']))
    rows.sort(key=lambda r: -r['win'])
    return rows


def main():
    summary = {}
    md = ['# Monopoly simulation results', '',
          'Generated by `analyze.py` from the JSON in `results/`. Win rates are outright wins (everyone else bankrupt); '
          'games still going after 1,000 rounds count as draws. ± is a 95% interval.', '']

    # ---- exact board probabilities
    mk = json.load(open(os.path.join(RES, 'markov.json')))
    md += ['## Where tokens end up (exact Markov chain, per roll)', '',
           '| Square | Leave jail at once | Stay in jail |', '|---|---|---|']
    order = sorted(range(40), key=lambda i: -mk['leave']['per_roll'][i])
    md.append('| In Jail | %.2f%% | %.2f%% |' % (pct(mk['leave']['per_roll'][40]), pct(mk['stay']['per_roll'][40])))
    for i in order[:12]:
        md.append('| %s | %.2f%% | %.2f%% |' % (NAMES[i], pct(mk['leave']['per_roll'][i]), pct(mk['stay']['per_roll'][i])))
    md.append('')
    summary['markov'] = mk

    # ---- game length by rules
    length = load('length')
    if length:
        md += ['## Game length and draws, four Yes-Men', '',
               '| Rules | Draws (no winner after 1,000 rounds) | Avg rounds to finish | Trades per game | First seat wins | Last seat wins |',
               '|---|---|---|---|---|---|']
        summary['length'] = {}
        for k in ['official', 'swaponly', 'notrade', 'noauction', 'family', 'kitchen']:
            if k not in length:
                continue
            d = length[k]
            fin = d['finished'] or 1
            sw = d['seat_wins']
            md.append('| %s | %.1f%% | %.1f | %.1f | %.1f%% | %.1f%% |' % (
                k, pct(d['timeouts'] / d['games']), d['avg_rounds_finished'], d['trades'] / d['games'],
                pct(sw[0] / fin), pct(sw[-1] / fin)))
            summary['length'][k] = dict(draws=d['timeouts'] / d['games'], rounds=d['avg_rounds_finished'],
                                        seat=[s / fin for s in sw], rounds_hist=d['rounds_hist_10'])
        md += ['', '| Players (official) | Draws | Avg rounds | First seat wins | Fair share |', '|---|---|---|---|---|']
        for n in range(2, 9):
            d = length.get('official_n%d' % n)
            if not d:
                continue
            fin = d['finished'] or 1
            md.append('| %d | %.1f%% | %.1f | %.1f%% | %.1f%% |' % (n, pct(d['timeouts'] / d['games']), d['avg_rounds_finished'],
                                                                pct(d['seat_wins'][0] / fin), 100.0 / n))
        md.append('')
        d = length.get('official')
        if d:
            rent = d['rent_by_square']
            tot = sum(rent)
            md += ['## Which squares collect the rent (four Yes-Men, official rules)', '',
                   '| Square | Share of all rent paid |', '|---|---|']
            for i in sorted(range(40), key=lambda i: -rent[i])[:12]:
                md.append('| %s | %.1f%% |' % (NAMES[i], pct(rent[i] / tot)))
            grp = {}
            for i in range(40):
                g = group_of(i)
                if g:
                    grp[g] = grp.get(g, 0) + rent[i]
            md += ['', '| Group | Share of all rent |', '|---|---|']
            for g in sorted(grp, key=lambda g: -grp[g]):
                md.append('| %s | %.1f%% |' % (g, pct(grp[g] / tot)))
            md.append('')
            # who wins: completed sets
            p = d['players']
            md += ['## Completing a set and winning (four Yes-Men, official rules)', '',
                   'A set can be completed more than once in a game (it changes hands when its owner goes bankrupt), '
                   'so the first column is completions per 100 games.', '',
                   '| Set | Completions per 100 games | Completer went on to win |', '|---|---|---|']
            summary['set_win'] = {}
            for g in GROUPS:
                c = sum(pl['sets'][g][0] for pl in p)
                w = sum(pl['sets'][g][1] for pl in p)
                md.append('| %s | %.0f | %.1f%% |' % (g, pct(c / d['games']), pct(w / c) if c else 0))
                summary['set_win'][g] = w / c if c else 0
            md.append('')

    # ---- one strategy against three Yes-Men
    tables = load('table')
    if tables:
        summary['table'] = {}
        for world in ['official', 'swaponly', 'notrade', 'noauction', 'family', 'kitchen']:
            rows = table_rows(tables, world)
            if not rows:
                continue
            summary['table'][world] = rows
            md += ['## One strategy against three Yes-Men: %s rules' % world, '',
                   '| Strategy | Win rate | Draws | Completed a set | Games |', '|---|---|---|---|---|']
            for r in rows:
                md.append('| %s | %.1f%% ± %.1f | %.1f%% | %.0f%% | %d |' % (r['label'], r['win'], r['ci'], r['draws'], r['got_set'], r['games']))
            md.append('')

    skip = load('skip')
    if skip:
        summary['skip'] = {}
        for world in ['official', 'family']:
            rows = table_rows(skip, world)
            if not rows:
                continue
            summary['skip'][world] = rows
            base = next((r for r in summary.get('table', {}).get(world, []) if r['strategy'] == 'everything'), None)
            md += ['## Buy everything except one group (vs three Yes-Men): %s rules' % world, '',
                   '| Skips | Win rate | vs Yes-Man |', '|---|---|---|']
            for r in rows:
                md.append('| %s | %.1f%% ± %.1f | %+.1f pts |' % (r['strategy'].replace('skip_', ''), r['win'], r['ci'],
                                                               r['win'] - (base['win'] if base else 25)))
            md.append('')

    # ---- colour duels
    duel = load('duel')
    if duel:
        summary['duel'] = {}
        for b in (5, 3):
            M = {}
            for a in GROUPS:
                for c in GROUPS:
                    if a == c:
                        continue
                    k1, k2 = 'b%d__%s__%s' % (b, a, c), 'b%d__%s__%s' % (b, c, a)
                    if k1 in duel:
                        d = duel[k1]
                        M[(a, c)] = d['players'][0]['wins'] / d['games']
                    elif k2 in duel:
                        d = duel[k2]
                        M[(a, c)] = d['players'][1]['wins'] / d['games']
            if not M:
                continue
            summary['duel']['b%d' % b] = {'%s>%s' % k: v for k, v in M.items()}
            avg = {a: sum(M[(a, c)] for c in GROUPS if c != a and (a, c) in M) / 7 for a in GROUPS}
            md += ['## Colour-set duels (two players, one set each, %s)' % ('hotels as fast as possible' if b == 5 else 'stop at three houses'), '',
                   'Row set beats column set this often.', '',
                   '| | ' + ' | '.join(GROUPS) + ' | average |', '|---' * 10 + '|']
            for a in sorted(GROUPS, key=lambda g: -avg[g]):
                md.append('| **%s** | ' % a + ' | '.join('—' if a == c else '%.0f%%' % pct(M.get((a, c), float('nan'))) for c in GROUPS) +
                          ' | %.0f%% |' % pct(avg[a]))
            md.append('')
        for size in (3, 4, 8):
            keys = [k for k in duel if k.startswith('royale%d' % size)]
            if not keys:
                continue
            wins = {g: 0.0 for g in GROUPS}
            seats = {g: 0 for g in GROUPS}
            for k in keys:
                d = duel[k]
                for pl in d['players']:
                    wins[pl['name']] += pl['wins'] / d['games']
                    seats[pl['name']] += 1
            share = {g: wins[g] / seats[g] for g in GROUPS if seats[g]}
            summary['duel']['royale%d' % size] = share
            md += ['## Every player gets one set: %d-player free-for-all (average win share over all tables)' % size, '',
                   '| Set | Win share | Fair share |', '|---|---|---|']
            for g in sorted(share, key=lambda g: -share[g]):
                md.append('| %s | %.1f%% | %.1f%% |' % (g, pct(share[g]), 100.0 / size))
            md.append('')

    # ---- head to head
    h2h = load('h2h')
    if h2h:
        summary['h2h'] = {}
        for world in ['official', 'family']:
            M = {}
            names = []
            for k, d in h2h.items():
                w, a, b = k.split('__')
                if w != world:
                    continue
                pa, pb = d['players'][0]['wins'] / d['games'], d['players'][1]['wins'] / d['games']
                M[(a, b)], M[(b, a)] = pa, pb
                for x in (a, b):
                    if x not in names:
                        names.append(x)
            if not M:
                continue
            summary['h2h'][world] = {'%s>%s' % k: v for k, v in M.items()}
            score = {a: sum(M.get((a, b), 0) for b in names if b != a) / (len(names) - 1) for a in names}
            names.sort(key=lambda a: -score[a])
            md += ['## Head to head, two players: %s rules' % world, '', 'Row strategy beats column strategy this often (draws excluded from neither).', '',
                   '| | ' + ' | '.join(names) + ' | average |', '|---' * (len(names) + 2) + '|']
            for a in names:
                md.append('| **%s** | ' % a + ' | '.join('—' if a == b else '%.0f%%' % pct(M.get((a, b), float('nan'))) for b in names) +
                          ' | %.0f%% |' % pct(score[a]))
            # non-transitive cycles a>b>c>a with each edge > 50% of decided games
            cyc = []
            for a in names:
                for b in names:
                    for c in names:
                        if len({a, b, c}) < 3 or not (a < b and a < c):
                            continue
                        if M.get((a, b), 0) > M.get((b, a), 0) and M.get((b, c), 0) > M.get((c, b), 0) and M.get((c, a), 0) > M.get((a, c), 0):
                            cyc.append((a, b, c))
            md += ['', 'Rock-paper-scissors cycles (A beats B beats C beats A): ' + (', '.join('%s > %s > %s > %s' % (a, b, c, a) for a, b, c in cyc) or 'none'), '']
            summary['h2h'][world + '_cycles'] = cyc

    # ---- number of players
    players = load('players')
    if players:
        summary['players'] = {}
        tests = sorted({k.split('__')[2] for k in players})
        md += ['## Does the best strategy change with the number of players? (one strategy vs the rest Yes-Men, official rules)', '',
               'Value: win rate divided by fair share (1/N). 1.00 = average.', '',
               '| Strategy | ' + ' | '.join('%d players' % n for n in range(2, 9)) + ' |', '|---' * 8 + '|']
        for t in tests:
            row = []
            for n in range(2, 9):
                d = players.get('official__n%d__%s' % (n, t))
                if d:
                    v = d['players'][0]['wins'] / d['games'] * n
                    row.append('%.2f' % v)
                    summary['players'].setdefault(t, {})[n] = v
                else:
                    row.append('')
            md.append('| %s | ' % LABEL.get(t, t) + ' | '.join(row) + ' |')
        md.append('')

    # ---- learned shark
    shark = load('shark')
    if shark:
        lv = json.load(open(os.path.join(RES, 'learned_values.json')))
        md += ['## Teaching the Shark (one strategy vs three Yes-Men, official rules)', '',
               'Learned set values: points of win rate a Yes-Man loses by never buying the set, x $100: ' +
               ', '.join('%s $%d' % kv for kv in sorted(lv.items(), key=lambda kv: -kv[1])), '',
               '| Player | Win rate |', '|---|---|']
        summary['shark'] = {}
        for k, lab in (('textbook', 'Shark, textbook values (expected rent at 3 houses)'), ('learned', 'Shark, learned values'),
                       ('champion_learned', 'Champion playbook, learned values'), ('allin_learned', 'All-In + learned-value trading'),
                       ('four_learned_sharks', 'Four learned Sharks at one table (each)')):
            if k in shark:
                d = shark[k]
                v = d['players'][0]['wins'] / d['games']
                summary['shark'][k] = v
                md.append('| %s | %.1f%% ± %.1f |' % (lab, pct(v), ci95(v, d['games'])))
        md.append('')

    # ---- evolution
    ev = os.path.join(RES, 'evolve')
    if os.path.exists(os.path.join(ev, 'stage1_history.json')):
        hist = json.load(open(os.path.join(ev, 'stage1_history.json')))
        summary['evolve_history'] = [(h['gen'], h['best'], h['median']) for h in hist]
        md += ['## Evolution (genetic algorithm, 24 strategies x %d generations, fitness = win rate vs three Yes-Men)' % len(hist), '',
               '| Generation | Best | Median |', '|---|---|---|']
        for h in hist:
            md.append('| %d | %.1f%% | %.1f%% |' % (h['gen'], pct(h['best']), pct(h['median'])))
        fp = os.path.join(ev, 'stage1_final.json')
        if os.path.exists(fp):
            fin = json.load(open(fp))
            summary['evolve_final'] = fin
            md += ['', 'Top evolved strategies re-tested on 200,000 games each:', '']
            for f in fin:
                md.append('- %.1f%%: `%s`' % (pct(f['fitness_200k']), f['spec']))
        lp = os.path.join(ev, 'stage2_lineage.json')
        if os.path.exists(lp):
            lin = json.load(open(lp))
            summary['evolve_lineage'] = lin
            md += ['', 'Arms race (each round evolves against three copies of the previous champion):', '']
            for l in lin:
                md.append('- round %d%s: `%s`' % (l['round'], (' (beat the previous champion %.1f%% of the time at a 4-seat table)' %
                                                           pct(l['vs_previous_200k'])) if 'vs_previous_200k' in l else '', l['spec']))
        md.append('')

    # ---- ecology: replicator dynamics over every 4-seat table
    eco = load('ecology')
    pool_path = os.path.join(RES, 'ecology_pool.json')
    if eco and os.path.exists(pool_path):
        pool = json.load(open(pool_path))
        k = len(pool)
        W = {}
        for key, d in eco.items():
            combo = tuple(int(x) for x in key[1:].split('_'))
            acc = {}
            for seat, i in enumerate(combo):
                acc.setdefault(i, []).append(d['players'][seat]['wins'] / d['games'])
            W[combo] = {i: sum(v) / len(v) for i, v in acc.items()}
        import itertools
        others = list(itertools.combinations_with_replacement(range(k), 3))
        coef = {}
        for m in others:
            c = [m.count(j) for j in range(k)]
            coef[m] = (math.factorial(3) / math.prod(math.factorial(x) for x in c), c)
        def fitness(x):
            f = [0.0] * k
            for i in range(k):
                for m in others:
                    mult, c = coef[m]
                    pm = mult * math.prod(x[j] ** c[j] for j in range(k) if c[j])
                    if pm == 0:
                        continue
                    T = tuple(sorted(m + (i,)))
                    f[i] += pm * W.get(T, {}).get(i, 0)
            return f
        x = [1.0 / k] * k
        traj = [x[:]]
        for gen in range(400):
            f = fitness(x)
            mean = sum(a * b for a, b in zip(x, f))
            x = [a * b / mean for a, b in zip(x, f)]
            traj.append(x[:])
        f0 = fitness([1.0 / k] * k)
        summary['ecology'] = {'pool': pool, 'traj': traj[::2], 'fitness_uniform': f0}
        md += ['## Ecology: a population of players evolving (replicator dynamics over all %d four-seat tables, 5,000-10,000 games each)' % len(W), '',
               'Each generation, strategies reproduce in proportion to how often they win at tables drawn at random from the current population.', '',
               '| Strategy | Win rate in an evenly mixed population | Share at start | after 25 gens | after 100 | after 400 |', '|---|---|---|---|---|---|']
        for i in sorted(range(k), key=lambda i: -traj[-1][i]):
            md.append('| %s | %.1f%% | %.1f%% | %.1f%% | %.1f%% | %.1f%% |' % (pool[i], pct(f0[i]), pct(traj[0][i]), pct(traj[25][i]), pct(traj[100][i]), pct(traj[-1][i])))
        md.append('')

    open(os.path.join(RES, 'summary.md'), 'w').write('\n'.join(md) + '\n')
    json.dump(summary, open(os.path.join(RES, 'summary.json'), 'w'), indent=1, default=str)
    print('\n'.join(md))


def group_of(i):
    g = {1: 'brown', 3: 'brown', 6: 'lightblue', 8: 'lightblue', 9: 'lightblue', 11: 'pink', 13: 'pink', 14: 'pink',
         16: 'orange', 18: 'orange', 19: 'orange', 21: 'red', 23: 'red', 24: 'red', 26: 'yellow', 27: 'yellow', 29: 'yellow',
         31: 'green', 32: 'green', 34: 'green', 37: 'darkblue', 39: 'darkblue', 5: 'railroads', 15: 'railroads',
         25: 'railroads', 35: 'railroads', 12: 'utilities', 28: 'utilities'}
    return g.get(i)


if __name__ == '__main__':
    main()
