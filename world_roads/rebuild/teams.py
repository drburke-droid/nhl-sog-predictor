def code_map(league):
    """{any code the franchise has had: today's code}"""
    out = {}
    for code, name, metro, old, moved in FRANCHISES[league]:
        out[code] = code
        for o in old:
            out[o] = code
    return out


def info(league):
    return {code: dict(name=name, metro=metro, moved=moved) for code, name, metro, old, moved in FRANCHISES[league]}
